// Turns the coverage and test-run JSON that Vitest writes into the Markdown shown in COVERAGE.md.
//
//   npm run coverage && npm run report

import { readFileSync, writeFileSync } from "node:fs";
import { relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const METRICS = ["statements", "branches", "functions", "lines"];

const percent = metric => `${metric.pct}%`;

export function buildReport({ summary, results, threshold, root }) {
  const { total, ...files } = summary;
  const rows = Object.entries(files)
    .map(([path, entry]) => [relative(root, path), entry])
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([path, entry]) => `| \`${path}\` | ${METRICS.map(m => percent(entry[m])).join(" | ")} |`);

  const totalRow = `| **Total** | ${METRICS.map(m => `**${percent(total[m])}**`).join(" | ")} |`;
  const met = METRICS.every(m => total[m].pct >= threshold);
  const passing = results.numFailedTests === 0;

  return `${[
    "# Test coverage",
    "",
    "| Tests | Passed | Failed |",
    "| ----- | ------ | ------ |",
    `| ${results.numTotalTests} | ${results.numPassedTests} | ${results.numFailedTests} |`,
    "",
    passing ? "✅ All tests pass." : "❌ Some tests fail.",
    "",
    "| File | Statements | Branches | Functions | Lines |",
    "| ---- | ---------- | -------- | --------- | ----- |",
    ...rows,
    totalRow,
    "",
    `Threshold: ${threshold}% on every metric — ${met ? "✅ met" : "❌ not met"}`,
    "",
    "_Generated by the [Tests workflow](.github/workflows/test.yml); do not edit by hand._",
  ].join("\n")}\n`;
}

async function main() {
  const { default: config } = await import("../vitest.config.js");
  const { thresholds } = config.test.coverage;
  const read = path => JSON.parse(readFileSync(path, "utf8"));

  const report = buildReport({
    summary: read("coverage/coverage-summary.json"),
    results: read("coverage/test-results.json"),
    threshold: Math.min(...Object.values(thresholds)),
    root: process.cwd(),
  });
  writeFileSync("COVERAGE.md", report);
  console.log("Wrote COVERAGE.md");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
